#!/usr/bin/env python3
"""Собирает архив «Троша на экране» для флешки: trosha/Trosha-na-ekrane-<метка>.zip.

Внутри папка «Троша-на-экране»: index.html, assets/ и файл КАК-ЗАПУСТИТЬ.txt. Архив лежит рядом со
страницей, поэтому скачивается с сайта: маленький-караван.рф/trosha/ (точная ссылка в README).
В имени архива стоит короткая метка содержимого: при любой правке имя новое, поэтому браузер и прокси не отдают
старую копию из кэша (так было с «Trosha-na-ekrane.zip»). Скрипт сам прописывает новую ссылку в README.
Поменяли что-то в trosha/ — запустите заново и закоммитьте архив:

    python3 tools/make_trosha_zip.py
"""
import hashlib
import io
import pathlib
import re
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1] / "trosha"
PREFIX = "Trosha-na-ekrane"
README_MD = ROOT.parent / "README.md"
FOLDER = "Троша-на-экране"
DATE = (2026, 1, 1, 0, 0, 0)    # одна и та же дата — архив не меняется, пока не изменились файлы

README = """Троша на экране панели — как запустить

1. Скопируйте папку целиком на флешку (или на компьютер панели). Внутри: index.html и папка assets.
2. Откройте файл index.html в браузере Edge (двойной щелчок или правой кнопкой: «Открыть с помощью» → Edge).
3. Нажмите на пульте кнопку ∨ (вниз). Страница сама развернётся на весь экран, появится Троша и заговорит.

Пульт (кликер):
  ∨  (Page Down)  — дальше
  ∧  (Page Up)    — назад, реплика повторяется
  □  (F5)         — на весь экран / обратно
Если пульт не срабатывает: пробел или Enter — дальше, Backspace — назад, нажатие мышью — дальше.
Клавиша H на клавиатуре показывает все клавиши; D — точки шагов; C — субтитры; B или точка — чёрный экран.

Порядок показа (на каждый шаг нажмите ∨):
  1. Троша: «Анна Григорьевна, у меня беда. Торопился к ребятам, и с моей попоны разлетелись все узорные лоскутки…»
  2. «Сейчас попробую.»  Экран сразу гаснет: он ЧЁРНЫЙ, дети заходят и Трошу пока не видят.
  3. (Дети пришли, Аня нажимает ∨) Троша появляется и здоровается: «Здравствуйте, ребята, это моя попона…»
  4. «Я помню три места…»  После этих слов на экране появляются фото: Свято-Троицкий собор, медресе Расулья,
     торговые ряды и пассаж Яушевых. Троша маленький, стоит в углу и слушает. Дети угадывают порядок.
  5. (Аня нажимает ∨) Экран становится ЧЁРНЫМ. Можно идти за подарком или собирать попону.
  6. (Аня нажимает ∨) Лоскутки слетаются на Трошу, он в целой попоне и говорит: «Теперь моя попона снова целая…
     Спасибо вам, ребята. Я приготовил для вас подарок.»  Троша остаётся на экране.
  7. (Аня нажимает ∨) Экран снова ЧЁРНЫЙ.
  Ещё нажатие ∨ — сначала.
Между шагами Троша ждёт столько, сколько нужно.

Звук включается после первого нажатия кнопки, это нормально для браузера.
"""


def add(z, name, data):
    info = zipfile.ZipInfo(f"{FOLDER}/{name}", DATE)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    z.writestr(info, data)


def build(files):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        add(z, "КАК-ЗАПУСТИТЬ.txt", README.encode("utf-8"))
        for p in files:
            add(z, p.relative_to(ROOT).as_posix(), p.read_bytes())
    return buf.getvalue()


def main():
    files = sorted(p for p in ROOT.rglob("*") if p.is_file() and not p.name.startswith(PREFIX))
    data = build(files)
    name = f"{PREFIX}-{hashlib.sha256(data).hexdigest()[:8]}.zip"
    for old in ROOT.glob(f"{PREFIX}*.zip"):
        old.unlink()
    (ROOT / name).write_bytes(data)
    md = README_MD.read_text(encoding="utf-8")
    # меняем только ссылки на файл на сайте (…/trosha/Trosha-na-ekrane-<метка>.zip); постоянную ссылку на релиз не трогаем
    md = re.sub(rf"trosha/{PREFIX}(-[0-9a-f]{{8}})?\.zip", f"trosha/{name}", md)
    README_MD.write_text(md, encoding="utf-8")
    print(f"{name}: {len(files)} файлов, {len(data) / 1e6:.1f} МБ; ссылка в README обновлена")


if __name__ == "__main__":
    main()
