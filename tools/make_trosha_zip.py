#!/usr/bin/env python3
"""Собирает архив «Троша на экране» для флешки: trosha/Trosha-na-ekrane.zip.

Внутри папка «Троша-на-экране»: index.html, assets/ и файл КАК-ЗАПУСТИТЬ.txt. Архив лежит рядом со
страницей, поэтому скачивается с сайта: маленький-караван.рф/trosha/Trosha-na-ekrane.zip.
Поменяли что-то в trosha/ — запустите заново и закоммитьте архив:

    python3 tools/make_trosha_zip.py
"""
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1] / "trosha"
OUT = ROOT / "Trosha-na-ekrane.zip"
FOLDER = "Троша-на-экране"
DATE = (2026, 1, 1, 0, 0, 0)    # одна и та же дата — архив не меняется, пока не изменились файлы

README = """Троша на экране панели — как запустить

1. Скопируйте папку целиком на флешку (или на компьютер панели). Внутри: index.html и папка assets.
2. Откройте файл index.html в браузере Edge (двойной щелчок или правой кнопкой: «Открыть с помощью» → Edge).
3. Нажмите на пульте кнопку ∨ (вниз). Страница сама развернётся на весь экран, появится Троша и заговорит.

Пульт (кликер):
  ∨  (Page Down)  — дальше
  ∧  (Page Up)    — назад, реплика повторяется
  □  (F5)         — на весь экран / обратно
Если пульт не срабатывает: пробел или Enter — дальше, Backspace — назад, нажатие мышью — дальше.
Клавиша H на клавиатуре показывает все клавиши; D — точки шагов; C — субтитры; B или точка — чёрный экран.

Порядок показа (на каждый шаг нажмите ∨):
  1. Троша: «Анна Григорьевна, вы готовитесь к занятию, а у меня проблема!»  (Аня спрашивает)
  2. «Я потерял попону!»  Троша остаётся на экране 12 секунд, пока Аня отвечает ему. Потом экран сам
     становится ЧЁРНЫМ: дети заходят и Трошу пока не видят. (Если Аня успела раньше, нажмите ∨ сразу.)
  3. (Дети пришли, Аня нажимает ∨) Троша появляется и здоровается: рассказ про лоскуты.
  4. «Ура! Иду с вами!»  (дети идут искать)
  5. Нашли первый лоскуток: «Ура, первый лоскуток нашёлся! …»
  6. Нашли сразу два: «Вот это да! Нашлись сразу два! Спасибо вам, ребята. Ищем дальше.»
  7. Нашли последний, татарский: «Вот он, татарский лоскуток! … Скорее собирайте мою попону!»
  8. (Дети собрали попону, Аня унесла её за экран) лоскуты слетаются на Трошу, он в попоне и благодарит.
  9. Экран гаснет. Ещё нажатие — сначала.
Между шагами Троша ждёт столько, сколько нужно.

Звук включается после первого нажатия кнопки, это нормально для браузера.
Время ожидания на шаге 2 можно поменять: откройте страницу с «?pause=секунды» в конце адреса,
например index.html?pause=20 (20 секунд). Если нажать ∨ раньше, страница идёт дальше сразу.
"""


def add(z, name, data):
    info = zipfile.ZipInfo(f"{FOLDER}/{name}", DATE)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    z.writestr(info, data)


def main():
    files = sorted(p for p in ROOT.rglob("*") if p.is_file() and p != OUT)
    with zipfile.ZipFile(OUT, "w") as z:
        add(z, "КАК-ЗАПУСТИТЬ.txt", README.encode("utf-8"))
        for p in files:
            add(z, p.relative_to(ROOT).as_posix(), p.read_bytes())
    print(f"{OUT.name}: {len(files)} файлов, {OUT.stat().st_size / 1e6:.1f} МБ")


if __name__ == "__main__":
    main()
